#!/usr/bin/env bash
# Resolves a headless-capable Blender for scripts/build-models.sh and prints its path.
# Usage: scripts/fetch-blender.sh            (prints path, downloads into .tools/blender/ if missing)
# Set BLENDER_BIN to use an existing install instead.
#
# Routes, by platform:
#   macOS arm64    official .dmg from blender.org (Blender 5 has no Intel Mac build)
#   Linux x86_64   official tarball from blender.org
#   Linux aarch64  blender.org publishes no Linux arm64 build, so Ubuntu's own blender package
#                  and the dependencies the host lacks are downloaded with the host's apt and
#                  unpacked, without root, under .tools/blender/root/. A wrapper script points
#                  Blender at that tree. The host must be Ubuntu, since the libraries are
#                  linked against its glibc and Python.
set -euo pipefail

BLENDER_VERSION="5.0.1"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="$ROOT/.tools/blender"

if [ -n "${BLENDER_BIN:-}" ]; then
  echo "$BLENDER_BIN"
  exit 0
fi

release_url="https://download.blender.org/release/Blender${BLENDER_VERSION%.*}"

fetch_macos() {
  binary="$DEST/Blender.app/Contents/MacOS/Blender"
  if [ ! -x "$binary" ]; then
    mkdir -p "$DEST"
    url="$release_url/blender-${BLENDER_VERSION}-macos-arm64.dmg"
    echo "Downloading $url" >&2
    curl -sSL -o "$DEST/blender.dmg" "$url"
    mount_point="$(mktemp -d)"
    hdiutil attach -quiet -nobrowse -mountpoint "$mount_point" "$DEST/blender.dmg"
    cp -R "$mount_point/Blender.app" "$DEST/"
    hdiutil detach -quiet "$mount_point"
    rm "$DEST/blender.dmg"
  fi
  echo "$binary"
}

fetch_linux_x64() {
  dir="$DEST/blender-${BLENDER_VERSION}-linux-x64"
  binary="$dir/blender"
  if [ ! -x "$binary" ]; then
    mkdir -p "$DEST"
    url="$release_url/blender-${BLENDER_VERSION}-linux-x64.tar.xz"
    echo "Downloading $url" >&2
    curl -sSL "$url" | tar -xJ -C "$DEST"
  fi
  echo "$binary"
}

fetch_ubuntu_arm64() {
  wrapper="$DEST/bin/blender"
  if [ -x "$wrapper" ]; then
    echo "$wrapper"
    return
  fi
  if ! grep -q '^ID=ubuntu' /etc/os-release 2>/dev/null; then
    echo "No Blender build for Linux arm64 outside Ubuntu; set BLENDER_BIN to a Blender install." >&2
    exit 1
  fi
  for tool in apt-get dpkg-deb python3 curl; do
    command -v "$tool" >/dev/null || { echo "$tool is needed to unpack Ubuntu's blender" >&2; exit 1; }
  done
  mkdir -p "$DEST/debs" "$DEST/apt/state/lists/partial" "$DEST/apt/cache/archives/partial"
  # apt with a private state and cache: it reads the host's sources and installed-package list,
  # so it resolves exactly the packages this host lacks, but needs no root.
  apt=(apt-get -o "Dir::State=$DEST/apt/state" -o "Dir::Cache=$DEST/apt/cache" -o Debug::NoLocking=1)
  echo "Resolving Ubuntu's blender package and its missing dependencies" >&2
  "${apt[@]}" update >/dev/null 2>&1 || true  # cleaning the system cache fails without root; harmless
  "${apt[@]}" install --print-uris -y --no-install-recommends blender python3-numpy \
    | grep "^'" | sed -E "s/^'([^']*)'.*/\1/" > "$DEST/uris.txt"
  if ! grep -q "/blender_${BLENDER_VERSION}" "$DEST/uris.txt"; then
    echo "Warning: Ubuntu ships $(grep -o 'blender_[^_]*' "$DEST/uris.txt" | head -1), not the pinned ${BLENDER_VERSION}" >&2
  fi
  echo "Downloading $(wc -l < "$DEST/uris.txt") packages" >&2
  (cd "$DEST/debs" && while read -r url; do
    file="${url##*/}"
    [ -f "$file" ] || curl -sSfO "$url"
  done < "$DEST/uris.txt")
  echo "Unpacking into $DEST/root" >&2
  rm -rf "$DEST/root"
  mkdir -p "$DEST/root"
  # Python's tarfile rather than GNU tar: tar's placeholder trick for symlinks fails on some
  # mounted filesystems (virtiofs).
  python3 - "$DEST" <<'EOF'
import glob, io, os, subprocess, sys, tarfile
dest = sys.argv[1]
for deb in sorted(glob.glob(os.path.join(dest, "debs", "*.deb"))):
    data = subprocess.run(["dpkg-deb", "--fsys-tarfile", deb], check=True, capture_output=True).stdout
    with tarfile.open(fileobj=io.BytesIO(data)) as archive:
        archive.extractall(os.path.join(dest, "root"), filter="fully_trusted")
EOF
  mkdir -p "$DEST/bin"
  cat > "$wrapper" <<EOF
#!/usr/bin/env bash
# Runs the Blender unpacked from Ubuntu's packages. Generated by scripts/fetch-blender.sh.
R="$DEST/root"
lib="\$R/usr/lib/aarch64-linux-gnu"
export LD_LIBRARY_PATH="\$lib:\$lib/pulseaudio:\$lib/blas:\$lib/lapack:\$R/usr/lib\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
export BLENDER_SYSTEM_RESOURCES="\$R/usr/lib/blender"
export PYTHONPATH="\$R/usr/lib/python3/dist-packages\${PYTHONPATH:+:\$PYTHONPATH}"
# --python-use-system-env lets Blender's Python see PYTHONPATH, where numpy lives.
exec "\$R/usr/bin/blender" --python-use-system-env "\$@"
EOF
  chmod +x "$wrapper"
  echo "$wrapper"
}

os="$(uname -s)"
arch="$(uname -m)"
case "$os" in
  Darwin)
    case "$arch" in
      arm64) fetch_macos ;;
      *) echo "Blender ${BLENDER_VERSION} has no macOS $arch build; set BLENDER_BIN" >&2; exit 1 ;;
    esac
    ;;
  Linux)
    case "$arch" in
      x86_64) fetch_linux_x64 ;;
      aarch64|arm64) fetch_ubuntu_arm64 ;;
      *) echo "unsupported arch: $arch" >&2; exit 1 ;;
    esac
    ;;
  *) echo "unsupported OS: $os" >&2; exit 1 ;;
esac
